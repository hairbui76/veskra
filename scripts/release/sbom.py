#!/usr/bin/env python3
"""REL-03 groundwork: SPDX 2.3 SBOM + third-party notice list for what Veskra ships.

Shipped Rust code = the normal-dependency closure of `veskra-ffi` (the Android cdylib), resolved
for target aarch64-linux-android. Android/Kotlin artifacts are taken from the version catalog
(declared, not resolved: the Android build cannot run in the authoring environment).

  python3 scripts/release/sbom.py   -> docs/release/sbom.spdx.json, docs/release/THIRD_PARTY_NOTICES.md
"""
import json, pathlib, re, subprocess, hashlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "docs" / "release"


def shipped_rust():
    meta = json.loads(subprocess.check_output(
        ["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", "aarch64-linux-android"],
        cwd=ROOT))
    pk = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    start = next(p["id"] for p in meta["packages"] if p["name"] == "veskra-ffi")
    seen, stack = set(), [start]
    while stack:
        cur = stack.pop()
        if cur in seen:
            continue
        seen.add(cur)
        for d in nodes[cur]["deps"]:
            if any(k["kind"] is None for k in d["dep_kinds"]):  # normal deps only
                stack.append(d["pkg"])
    ws = set(meta["workspace_members"])
    return sorted((pk[i] for i in seen), key=lambda p: (p["id"] not in ws, p["name"])), ws


def catalog():
    text = (ROOT / "apps/android/gradle/libs.versions.toml").read_text()
    versions = dict(re.findall(r'^([\w-]+)\s*=\s*"([^"]+)"', text.split("[libraries]")[0], re.M))
    libs = []
    for name, body in re.findall(r'^([\w-]+)\s*=\s*\{([^}]*)\}', text.split("[libraries]")[1].split("[plugins]")[0], re.M):
        mod = re.search(r'module\s*=\s*"([^"]+)"', body)
        ref = re.search(r'version\.ref\s*=\s*"([^"]+)"', body)
        ver = re.search(r'version\s*=\s*"([^"]+)"', body)
        if mod:
            libs.append((mod.group(1), versions.get(ref.group(1)) if ref else (ver.group(1) if ver else "BOM-managed")))
    return libs


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    rust, ws = shipped_rust()
    android = catalog()
    pkgs, rows = [], []
    for p in rust:
        first_party = p["id"] in ws
        lic = p.get("license") or "NOASSERTION"
        spdx_id = "SPDXRef-Rust-" + re.sub(r"[^A-Za-z0-9.-]", "-", f"{p['name']}-{p['version']}")
        pkgs.append({"SPDXID": spdx_id, "name": p["name"], "versionInfo": p["version"],
                     "downloadLocation": "NONE" if first_party else f"https://crates.io/crates/{p['name']}/{p['version']}",
                     "licenseDeclared": lic, "licenseConcluded": "MIT OR Apache-2.0" if first_party else "NOASSERTION",
                     "supplier": "Organization: Veskra contributors" if first_party else "NOASSERTION",
                     "externalRefs": [] if first_party else [{"referenceCategory": "PACKAGE-MANAGER",
                                                               "referenceType": "purl",
                                                               "referenceLocator": f"pkg:cargo/{p['name']}@{p['version']}"}]})
        if not first_party:
            rows.append((p["name"], p["version"], lic, p.get("repository") or ""))
    for mod, ver in android:
        g, a = mod.split(":")
        pkgs.append({"SPDXID": "SPDXRef-Maven-" + re.sub(r"[^A-Za-z0-9.-]", "-", f"{a}-{ver}"), "name": mod,
                     "versionInfo": ver, "downloadLocation": "NOASSERTION", "licenseDeclared": "NOASSERTION",
                     "licenseConcluded": "NOASSERTION", "supplier": "NOASSERTION",
                     "comment": "Declared in apps/android/gradle/libs.versions.toml; not resolved (Android build blocked, B-1)",
                     "externalRefs": [{"referenceCategory": "PACKAGE-MANAGER", "referenceType": "purl",
                                       "referenceLocator": f"pkg:maven/{g}/{a}@{ver}"}]})
    lock_hash = hashlib.sha256((ROOT / "Cargo.lock").read_bytes()).hexdigest()
    doc = {"spdxVersion": "SPDX-2.3", "dataLicense": "CC0-1.0", "SPDXID": "SPDXRef-DOCUMENT",
           "name": "veskra-android-shipped-components",
           "documentNamespace": f"https://veskra.invalid/spdx/{lock_hash[:16]}",
           "creationInfo": {"created": "2026-10-09T00:00:00Z", "creators": ["Tool: scripts/release/sbom.py"],
                            "comment": f"Cargo.lock sha256 {lock_hash}"},
           "packages": pkgs}
    (OUT / "sbom.spdx.json").write_text(json.dumps(doc, indent=2) + "\n")
    lines = ["# Third-party notices (Rust components shipped in libveskra_ffi.so)", "",
             "Generated by `scripts/release/sbom.py` from `Cargo.lock`. License texts are distributed with each",
             "crate (crates.io source archive). Where a crate offers a choice, Veskra uses it under MIT or",
             "Apache-2.0 (never LGPL). Android/Kotlin libraries are listed in `sbom.spdx.json` (declared only;",
             "their notices must be generated by the Android build, REL-03).", "",
             "| Crate | Version | License (as declared) | Repository |", "|---|---|---|---|"]
    lines += [f"| {n} | {v} | {l} | {r} |" for n, v, l, r in rows]
    (OUT / "THIRD_PARTY_NOTICES.md").write_text("\n".join(lines) + "\n")
    print(f"{len(rows)} third-party Rust crates shipped, {len(android)} declared Android libraries")


main()
