def swatches() -> list[tuple[str, str, tuple[int, int, int]]]:
    """Fixed swatch set: primaries, secondaries, neutral ramp, near-black, skin-like,
    desaturated, saturated and a 5x5x5 grid (duplicates removed, first occurrence wins)."""
    groups: list[tuple[str, list[tuple[int, int, int]]]] = [
        ("primary", [(255, 0, 0), (0, 255, 0), (0, 0, 255), (128, 0, 0), (0, 128, 0), (0, 0, 128)]),
        ("secondary", [(0, 255, 255), (255, 0, 255), (255, 255, 0), (0, 128, 128), (128, 0, 128), (128, 128, 0)]),
        ("neutral", [(v, v, v) for v in (0, 1, 2, 3, 5, 8, 12, 17, 23, 32, 45, 64, 80, 96, 112, 128, 144, 160,
                                         176, 192, 208, 224, 240, 250, 253, 254, 255)]),
        ("near-black", [(1, 0, 0), (0, 1, 0), (0, 0, 1), (2, 1, 3), (5, 3, 1), (8, 8, 4), (10, 0, 12), (16, 8, 0)]),
        ("skin-like", [(255, 224, 196), (241, 194, 167), (224, 172, 105), (198, 134, 66), (141, 85, 36),
                       (92, 51, 23), (255, 205, 148), (234, 192, 134), (255, 173, 96), (197, 140, 133),
                       (161, 102, 94), (80, 51, 53)]),
        ("desaturated", [(120, 130, 125), (140, 120, 110), (100, 110, 140), (180, 170, 150), (90, 100, 95),
                         (200, 190, 210), (60, 70, 65), (150, 160, 170)]),
        ("saturated", [(200, 30, 40), (30, 200, 60), (40, 60, 220), (250, 140, 0), (140, 0, 250), (0, 180, 180),
                       (230, 20, 140), (120, 220, 20)]),
        ("grid", [(r, g, b) for r in (0, 64, 128, 192, 255) for g in (0, 64, 128, 192, 255)
                  for b in (0, 64, 128, 192, 255)]),
    ]
    seen: set[tuple[int, int, int]] = set()
    out = []
    for cat, cols in groups:
        for c in cols:
            if c in seen:
                continue
            seen.add(c)
            out.append((f"{cat}-{len(out):03d}", cat, c))
    return out


def lcms_profile(path: Path) -> tuple[ImageCms.ImageCmsProfile, dict]:
    data = path.read_bytes()
    info = {"file": str(path.relative_to(FIX)), "bytes": len(data), "sha256": hashlib.sha256(data).hexdigest()}
    prof = ImageCms.ImageCmsProfile(io.BytesIO(data))  # raises PyCMSError if LittleCMS rejects it
    p = prof.profile
    info.update(
        lcms_open_ok=True,
        lcms_description=ImageCms.getProfileDescription(prof).strip(),
        lcms_copyright=(p.copyright or "").strip(),
        lcms_version=p.version,
        lcms_is_matrix_shaper=bool(p.is_matrix_shaper),
        lcms_media_white_point=list(p.media_white_point[0]),
        lcms_colorants=[list(p.red_colorant[0]), list(p.green_colorant[0]), list(p.blue_colorant[0])],
        lcms_intents_supported={
            name: bool(ImageCms.isIntentSupported(prof, intent, ImageCms.Direction.OUTPUT))
            for name, intent in [("perceptual", ImageCms.Intent.PERCEPTUAL),
                                 ("relative-colorimetric", ImageCms.Intent.RELATIVE_COLORIMETRIC),
                                 ("saturation", ImageCms.Intent.SATURATION),
                                 ("absolute-colorimetric", ImageCms.Intent.ABSOLUTE_COLORIMETRIC)]
        },
    )
    # ICC v4 Profile ID: MD5 with flags (44..48), intent (64..68) and ID (84..100) zeroed.
    if len(data) >= 128:
        z = bytearray(data)
        z[44:48] = b"\0" * 4
        z[64:68] = b"\0" * 4
        z[84:100] = b"\0" * 16
        stored = data[84:100]
        info["header_profile_id"] = stored.hex()
        info["md5_profile_id_ok"] = stored == b"\0" * 16 or hashlib.md5(bytes(z)).digest() == stored
    return prof, info


def lcms_convert(src, dst, rgb: list[tuple[int, int, int]], intent, flags) -> list[list[int]]:
    t = ImageCms.buildTransform(src, dst, "RGB", "RGB", renderingIntent=intent, flags=flags)
    im = Image.new("RGB", (len(rgb), 1))
    im.putdata([tuple(c) for c in rgb])
    out = ImageCms.applyTransform(im, t)
    return [list(out.getpixel((i, 0))) for i in range(len(rgb))]


def colourspace(name: str):
    """colour-science colourspace with the RGB<->XYZ matrices *derived* from the chromaticities
    (normalised primary matrix). colour-science's built-in "sRGB" otherwise uses the IEC
    61966-2.1 matrix rounded to 4 decimals; Veskra and LittleCMS both derive the matrix from the
    published chromaticities, so the derived form is the like-for-like reference. The deviation
    caused by the rounded matrix is recorded separately in the JSON (`notes`)."""
    cs = colour.RGB_COLOURSPACES[name].copy()
    cs.use_derived_transformation_matrices(True)
    return cs


def colour_lab(rgb8: np.ndarray, space: str, derived: bool = True) -> np.ndarray:
    cs = colourspace(space) if derived else colour.RGB_COLOURSPACES[space]
    xyz = colour.RGB_to_XYZ(rgb8 / 255.0, cs, illuminant=D50_XY,
                            chromatic_adaptation_transform="Bradford", apply_cctf_decoding=True)
    return colour.XYZ_to_Lab(xyz, illuminant=D50_XY)


def _round(v):
    """12 significant digits: far below every tolerance used by the Rust tests, keeps diffs small."""
    if isinstance(v, float):
        return float(f"{v:.12g}")
    if isinstance(v, list):
        return [_round(x) for x in v]
    if isinstance(v, dict):
        return {k: _round(x) for k, x in v.items()}
    return v


def dump_json(doc) -> str:
    """Indented JSON with numeric arrays kept on one line (diff-friendly, ~half the size)."""
    text = json.dumps(_round(doc), indent=1)
    text = re.sub(r"\[\s*([-0-9.eE,\s]+?)\s*\]", lambda m: "[" + ",".join(x.strip() for x in m.group(1).split(",")) + "]",
                  text)
    return text + "\n"


def main() -> int:
    for f in ("veskra-srgb-v4.icc", "veskra-display-p3-v4.icc"):
        if not (ICC / f).exists():
            print(f"missing {ICC / f}; run the icc_fixtures test with VESKRA_REGEN_COLOR_FIXTURES=1", file=sys.stderr)
            return 2

    # LittleCMS's own built-in sRGB (third-party implementation of the same colorimetry).
    # LittleCMS stamps the current time into header bytes 24..36 and leaves the Profile ID zero;
    # the date is normalized to 2026-01-01T00:00:00 so the fixture is reproducible (the date is
    # informational and not covered by any checksum since the Profile ID is zero).
    builtin = bytearray(ImageCms.ImageCmsProfile(ImageCms.createProfile("sRGB")).tobytes())
    if builtin[84:100] != b"\0" * 16:
        print("unexpected non-zero Profile ID in LittleCMS built-in sRGB", file=sys.stderr)
        return 4
    builtin[24:36] = bytes([0x07, 0xEA, 0, 1, 0, 1, 0, 0, 0, 0, 0, 0])
    (ICC / "lcms2-builtin-srgb.icc").write_bytes(bytes(builtin))

    profiles = {}
    handles = {}
    for key, f in [("veskra_srgb", "veskra-srgb-v4.icc"), ("veskra_p3", "veskra-display-p3-v4.icc"),
                   ("lcms_builtin_srgb", "lcms2-builtin-srgb.icc")]:
        handles[key], profiles[key] = lcms_profile(ICC / f)

    sw = swatches()
    rgb = [list(c) for _, _, c in sw]
    rgb_np = np.array(rgb, dtype=np.float64)
    lab_srgb = colour_lab(rgb_np, "sRGB")
    lab_p3 = colour_lab(rgb_np, "Display P3")
    lab_srgb_iec = colour_lab(rgb_np, "sRGB", derived=False)
    iec_dev = float(np.max(np.abs(lab_srgb_iec - lab_srgb)))
    p3_float = colour.RGB_to_RGB(rgb_np / 255.0, colourspace("sRGB"),
                                 colourspace("Display P3"), chromatic_adaptation_transform=None,
                                 apply_cctf_decoding=True, apply_cctf_encoding=True)

    I = ImageCms.Intent
    F = ImageCms.Flags
    conv_specs = [
        ("veskra_srgb", "veskra_p3", "relative-colorimetric", I.RELATIVE_COLORIMETRIC, "default", F.NONE),
        ("veskra_srgb", "veskra_p3", "relative-colorimetric", I.RELATIVE_COLORIMETRIC, "NOOPTIMIZE", F.NOOPTIMIZE),
        ("veskra_p3", "veskra_srgb", "relative-colorimetric", I.RELATIVE_COLORIMETRIC, "default", F.NONE),
        ("veskra_p3", "veskra_srgb", "relative-colorimetric", I.RELATIVE_COLORIMETRIC, "NOOPTIMIZE", F.NOOPTIMIZE),
        ("veskra_srgb", "veskra_p3", "perceptual", I.PERCEPTUAL, "NOOPTIMIZE", F.NOOPTIMIZE),
        ("veskra_srgb", "veskra_p3", "absolute-colorimetric", I.ABSOLUTE_COLORIMETRIC, "NOOPTIMIZE", F.NOOPTIMIZE),
        ("lcms_builtin_srgb", "veskra_p3", "relative-colorimetric", I.RELATIVE_COLORIMETRIC, "NOOPTIMIZE",
         F.NOOPTIMIZE),
        ("veskra_srgb", "veskra_srgb", "relative-colorimetric", I.RELATIVE_COLORIMETRIC, "default", F.NONE),
        ("lcms_builtin_srgb", "veskra_srgb", "relative-colorimetric", I.RELATIVE_COLORIMETRIC, "NOOPTIMIZE",
         F.NOOPTIMIZE),
    ]
    conversions = []
    for src, dst, intent_name, intent, flag_name, flags in conv_specs:
        conversions.append({
            "name": f"{src}->{dst}/{intent_name}/{flag_name}",
            "src": src, "dst": dst, "intent": intent_name, "lcms_flags": flag_name,
            "output8": lcms_convert(handles[src], handles[dst], rgb, intent, flags),
        })

    # CIEDE2000 cross-checks with colour-science: Sharma pairs + consecutive swatch pairs.
    sharma = []
    for row in SHARMA:
        a, b = np.array(row[:3]), np.array(row[3:6])
        d = float(colour.delta_E(a, b, method="CIE 2000"))
        if abs(d - row[6]) > 5e-5:
            print(f"colour-science disagrees with typed Sharma value {row}: {d}", file=sys.stderr)
            return 3
        sharma.append({"lab1": list(row[:3]), "lab2": list(row[3:6]), "published": row[6], "colour": d})
    pairs = []
    for i in range(len(sw)):
        j = (i * 7 + 3) % len(sw)
        pairs.append({"i": i, "j": j, "de00": float(colour.delta_E(lab_srgb[i], lab_srgb[j], method="CIE 2000"))})

    doc = {
        "generator": "scripts/color/gen_oracle_fixtures.py",
        "tools": {
            "python": platform.python_version(),
            "pillow": PIL.__version__,
            "littlecms": ImageCms.core.littlecms_version,
            "colour_science": colour.__version__,
            "numpy": np.__version__,
        },
        "lab_white_xyz": D50_XYZ.tolist(),
        "lab_definition": "CIELAB with ICC PCS D50 white; sRGB/P3 -> XYZ D50 via colour-science, Bradford, "
                          "exact cctf decoding",
        "notes": {
            "srgb_matrix": "derived from chromaticities (as Veskra and LittleCMS)",
            "max_abs_dlab_if_iec_rounded_srgb_matrix_were_used": iec_dev,
        },
        "profiles": profiles,
        "swatches": [
            {"id": sid, "category": cat, "rgb8": list(c), "lab_d50_srgb": lab_srgb[i].tolist(),
             "lab_d50_if_p3": lab_p3[i].tolist(), "colour_srgb_to_p3_float": p3_float[i].tolist()}
            for i, (sid, cat, c) in enumerate(sw)
        ],
        "conversions": conversions,
        "ciede2000_sharma": sharma,
        "ciede2000_swatch_pairs": pairs,
    }
    (FIX / "expected_conversions.json").write_text(dump_json(doc))

    with open(FIX / "srgb_swatches.csv", "w", newline="") as fh:
        w = csv.writer(fh, lineterminator="\n")
        w.writerow(["id", "category", "r8", "g8", "b8", "lab_d50_L", "lab_d50_a", "lab_d50_b"])
        for i, (sid, cat, c) in enumerate(sw):
            w.writerow([sid, cat, *c, *(f"{v:.6f}" for v in lab_srgb[i])])

    print(f"tools: {doc['tools']}")
    for k, v in profiles.items():
        print(f"{k}: open_ok={v['lcms_open_ok']} desc={v['lcms_description']!r} "
              f"md5_profile_id_ok={v.get('md5_profile_id_ok')} sha256={v['sha256'][:16]}..")
    print(f"swatches: {len(sw)}; conversions: {len(conversions)}; sharma pairs verified: {len(sharma)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
