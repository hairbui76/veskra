"""Generate independent color-oracle fixtures for veskra-color (COL-008, SPK-05, CLR-02).

Oracles (test-time tools only; nothing here ships in Veskra):
  * LittleCMS 2 via Pillow's ``PIL.ImageCms`` -- ICC transforms and an independent check that
    Veskra's generated ICC profiles are readable by a mature CMM.
  * colour-science -- reference CIELAB D50 values, float sRGB -> Display P3 conversion and
    CIEDE2000.

Inputs:
  tests/fixtures/color/icc/veskra-srgb-v4.icc        generated by veskra-color (see LICENSES.md)
  tests/fixtures/color/icc/veskra-display-p3-v4.icc  generated by veskra-color

Outputs (deterministic for a given tool-version set; versions are recorded in the JSON):
  tests/fixtures/color/icc/lcms2-builtin-srgb.icc    LittleCMS cmsCreate_sRGBProfile() output
  tests/fixtures/color/srgb_swatches.csv             swatch set + colour-science Lab D50
  tests/fixtures/color/expected_conversions.json     all oracle values consumed by
                                                     crates/veskra-color/tests/oracle.rs

Usage (from the repository root):
  VESKRA_REGEN_COLOR_FIXTURES=1 cargo test -p veskra-color --test icc_fixtures   # ICC files
  python3 -I scripts/color/gen_oracle_fixtures.py
  cargo test -p veskra-color --test oracle -- --nocapture

Exits non-zero if LittleCMS cannot open a generated profile or a self-check fails.
"""

